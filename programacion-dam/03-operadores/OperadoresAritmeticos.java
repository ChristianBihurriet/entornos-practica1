public class OperadoresAritmeticos {

    public static void main(String[] args) {
        int numeroA = 8;
        int numeroB = 3;

        System.out.println("Suma (+): " + (numeroA + numeroB));
        System.out.println("Resta (-): " + (numeroA - numeroB));
        System.out.println("Multiplicación (*): " + (numeroA * numeroB));
        System.out.println("División (/): " + (numeroA / numeroB));
        System.out.println("Resto de la división (%): " + (numeroA % numeroB));

        // ¿Qué resultados esperas si numeroA vale 10 y numeroB vale 4?
        // Los paréntesis permiten que Java calcule antes la operación numérica.
    }
}

